"""
Scale & Concurrency Benchmark Route: GET /v1/scale
Serves real measured load-test results, cascade statistics, and 1M-calls sizing data.
Strictly adheres to Rule 1: No fabricated metrics; unmeasured returns clear status.
"""

import os
import json
from fastapi import APIRouter

router = APIRouter(prefix="/v1", tags=["Scalability"])


@router.get("/scale")
async def get_scale_benchmarks():
    """
    Returns empirical load-test results generated by backend/run_load_test.py.
    Includes concurrency scaling curves, p50/p95/p99 latency, CPU utilization,
    Stage 2 escalation rates, and hardware sizing projections for 1 million calls.
    """
    base_dir = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    results_path = os.path.join(base_dir, "scale_results.json")

    if not os.path.exists(results_path):
        return {
            "status": "not_measured",
            "message": "Empirical load test not yet executed. Run 'python backend/run_load_test.py' to generate.",
            "concurrency_benchmarks": [],
            "million_calls_projection": None
        }

    try:
        with open(results_path, "r", encoding="utf-8") as f:
            data = json.load(f)
            data["status"] = "measured"
            return data
    except Exception as e:
        return {
            "status": "error",
            "message": f"Failed reading scale results: {str(e)}"
        }
